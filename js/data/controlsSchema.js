const BY_KEY = Object.fromEntries(CONTROLS.map((c) => [c.k, c]));

/** يتحقق من قيمة واحدة ويعيدها مصحّحة، أو undefined إن كانت غير صالحة */
export function cleanValue(c, v) {
  if (c.type === 'bool') return typeof v === 'boolean' ? v : undefined;
  if (c.type === 'num') { const x = Math.round(Number(v)); return Number.isFinite(x) ? Math.min(c.max, Math.max(c.min, x)) : undefined; }
  if (c.type === 'text') return typeof v === 'string' ? v.replace(/[\u0000-\u001F<>]/g, '').trim().slice(0, c.max) : undefined;
  if (c.type === 'select') return c.options.some((o) => o[0] === v) ? v : undefined;
  return undefined;
}

/** يعيد كائن التغييرات فقط (ما يختلف عن الافتراضي) بعد التحقق — يُستعمل في الخادم وفي الواجهة */
export function cleanControls(input) {
  const out = {};
  for (const [k, v] of Object.entries(input || {})) {
    const c = BY_KEY[k]; if (!c || c.type === 'action') continue;
    const x = cleanValue(c, v);
    if (x !== undefined && x !== c.def) out[k] = x;
  }
  return out;
}
